// Exported so tests can assert key-set parity across every language.
export const dictionaries = { ko, en, es, pt, ja, zh };
let current = "ko";

export function setLang(lang) {
  if (dictionaries[lang]) current = lang;
  // Keep the document language in sync for accessibility / font selection.
  if (typeof document !== "undefined") document.documentElement.lang = current;
}

export function getLang() {
  return current;
}

export function availableLangs() {
  return Object.keys(dictionaries);
}

export function t(key, params) {
  let str = dictionaries[current][key] ?? ko[key];
  if (str === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}
